-- Bidirectional helper — every traversal query should read from this.
CREATE OR REPLACE VIEW v_edge_bi AS
  SELECT from_node AS a, to_node AS b, km FROM grid_edge
  UNION ALL
  SELECT to_node   AS a, from_node AS b, km FROM grid_edge;

