-- ---------------------------------------------------------------------
-- 4. PRECOMPUTED ROUTES  (7 GenCos x 26 destinations = 182)
--    Regenerate with the recursive query in section 6 if the network changes.
-- ---------------------------------------------------------------------
CREATE TABLE route (
  route_id      integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  genco         text NOT NULL REFERENCES genco(name),
  dest_name     text NOT NULL,
  dest_kind     text NOT NULL CHECK (dest_kind IN ('offtaker','disco')),
  injection_node text NOT NULL REFERENCES substation(name),
  routed_km     numeric(8,1) NOT NULL,   -- grid only, excludes last mile
  last_mile_km  numeric(7,1) NOT NULL,
  hop_count     integer NOT NULL,
  UNIQUE (genco, dest_name)
);

CREATE TABLE route_hop (
  route_id  integer NOT NULL REFERENCES route(route_id) ON DELETE CASCADE,
  seq       integer NOT NULL,
  from_node text NOT NULL REFERENCES substation(name),
  to_node   text NOT NULL REFERENCES substation(name),
  km        numeric(8,2) NOT NULL,
  PRIMARY KEY (route_id, seq)
);

