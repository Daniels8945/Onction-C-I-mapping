-- =====================================================================
-- ONCTION GRID ATLAS — portable schema + seed data
-- GenCo / DisCo / Offtaker connection mapping over the Nigerian TCN network
-- Generated 2026-08-20 from the analysis in the Cowork project.
--
-- Targets PostgreSQL. For SQLite: drop the two CREATE VIEW ... RECURSIVE
-- notes below (SQLite supports WITH RECURSIVE the same way), replace
-- GENERATED ALWAYS AS IDENTITY with INTEGER PRIMARY KEY AUTOINCREMENT,
-- and replace numeric(...) with REAL.
--
-- METHOD NOTES (carry these forward — they are assumptions, not facts):
--   * routed_km = Dijkstra shortest path over grid_edge, a SIMPLIFIED model
--     of Nigeria's 330kV backbone. Good to roughly +/-10%. Not for settlement.
--   * loss_pct = fixed_pct + km/100 * per_100km_pct  (see loss_model).
--     This is a SCREENING figure, NOT a NERC loss factor. Replace with the
--     PPA Schedule 3 loss factor when available.
--   * 132kV substation coordinates are placed from locality, not surveyed.
--   * last_mile_km is straight-line substation -> site, +/-3 km.
-- =====================================================================

DROP VIEW IF EXISTS v_energy_projection;
DROP VIEW IF EXISTS v_best_source;
DROP VIEW IF EXISTS v_route_lookup;
DROP TABLE IF EXISTS route_hop;
DROP TABLE IF EXISTS route;
DROP TABLE IF EXISTS offtaker;
DROP TABLE IF EXISTS disco;
DROP TABLE IF EXISTS genco;
