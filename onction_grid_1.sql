CREATE TABLE disco (
  name            text PRIMARY KEY,
  lat             numeric(9,6) NOT NULL,
  lon             numeric(9,6) NOT NULL,
  injection_node  text NOT NULL REFERENCES substation(name),
  contracted      text,
  upstream_source text,
  last_mile_km    numeric(7,1)
);

CREATE TABLE offtaker (
  name            text PRIMARY KEY,
  capacity_mw     numeric(7,2) NOT NULL,
  lat             numeric(9,6) NOT NULL,
  lon             numeric(9,6) NOT NULL,
  location        text,
  injection_node  text NOT NULL REFERENCES substation(name),
  last_mile_km    numeric(7,1) NOT NULL
);

