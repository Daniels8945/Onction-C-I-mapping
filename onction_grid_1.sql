CREATE TABLE genco (
  name             text PRIMARY KEY,
  lat              numeric(9,6) NOT NULL,
  lon              numeric(9,6) NOT NULL,
  connection_node  text NOT NULL REFERENCES substation(name),
  capacity_note    text,
  commitment       text,          -- FREE | committed | over-committed | earmarked
  tariff_ngn_kwh   numeric(8,2)   -- invoice rate in use (MYTO-adjusted), not contract rate
