-- 5. VIEWS — the lookup table and the projection
-- ---------------------------------------------------------------------

-- 5a. The lookup matrix. One row per GenCo x destination pair.
CREATE VIEW v_route_lookup AS
SELECT
  r.genco,
  r.dest_name,
  r.dest_kind,
  r.injection_node,
  r.routed_km,
  r.last_mile_km,
  r.routed_km + r.last_mile_km                                   AS total_km,
  lm.fixed_pct + (r.routed_km / 100.0) * lm.per_100km_pct        AS loss_pct,
  g.commitment,
  g.tariff_ngn_kwh,
  COALESCE(o.capacity_mw, 0)                                     AS dest_mw
FROM route r
JOIN genco g            ON g.name = r.genco
LEFT JOIN offtaker o    ON o.name = r.dest_name AND r.dest_kind = 'offtaker'
CROSS JOIN loss_model lm
WHERE lm.is_default;

-- 5b. Nearest source for every destination.
CREATE VIEW v_best_source AS
SELECT DISTINCT ON (dest_name)
  dest_name, dest_kind, dest_mw, genco, commitment,
  routed_km, loss_pct, injection_node
FROM v_route_lookup
ORDER BY dest_name, routed_km ASC;
-- SQLite equivalent (no DISTINCT ON):
--   SELECT * FROM (SELECT *, ROW_NUMBER() OVER (PARTITION BY dest_name ORDER BY routed_km) rn
--                  FROM v_route_lookup) WHERE rn = 1;

-- 5c. Energy projection at each destination's own contracted capacity,
--     24 h/day, 30-day month, under every AT&C&C scenario.
CREATE VIEW v_energy_projection AS
SELECT
  l.genco,
  l.dest_name,
  a.code                                                        AS atcc_scenario,
  a.atcc_pct,
  l.routed_km,
  l.loss_pct,
  l.dest_mw,
  (l.dest_mw * 1000 * 24 * 30)                                  AS contracted_kwh,
  (l.dest_mw * 1000 * 24 * 30) * (1 - l.loss_pct/100.0)         AS delivered_kwh,
  (l.dest_mw * 1000 * 24 * 30) * (1 - l.loss_pct/100.0)
                                * (1 - a.atcc_pct/100.0)        AS recovered_kwh,
  (l.dest_mw * 1000 * 24 * 30) * (l.loss_pct/100.0)             AS transmission_loss_kwh,
  (l.dest_mw * 1000 * 24 * 30) * (1 - l.loss_pct/100.0)
                                * (a.atcc_pct/100.0)            AS atcc_loss_kwh
FROM v_route_lookup l
CROSS JOIN atcc_scenario a
WHERE l.dest_mw > 0;

